def _acute_danger(text: str) -> bool:
    return (
        contains_keyword(text, ACUTE_BLEEDING_KEYWORDS)
        or contains_keyword(text, ACUTE_ALLERGY_KEYWORDS)
        or contains_keyword(text, ACUTE_DETERIORATION_KEYWORDS)
        or LIFE_THREAT(text)
        or (contains_keyword(text, PAIN_INTENSITY_KEYWORDS) and contains_keyword(text, PAIN_WORDS))
    )


