def build_system_prompt(question_type: object = None) -> str:
    """Собирает system prompt только с релевантным блоком под тип ответа."""

    normalized_type = str(question_type or "").strip()
    type_prompt = QUESTION_TYPE_PROMPTS.get(normalized_type, GENERAL_ANSWER_PROMPT)
    return f"{BASE_SYSTEM_PROMPT}\n\n{type_prompt}"


