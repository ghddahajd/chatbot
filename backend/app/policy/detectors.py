"""датчики сигналов: по тексту сообщения понять, есть ли в нём кризис, жалоба, срочный симптом и т.п.

У каждого датчика в одном месте слова, исключения и примеры. examples_yes обязаны сработать,
examples_no — нет: test_detectors.py проверяет примеры всех датчиков, а сеть безопасности (слой А)
берёт их в корпус. Нашли ложное срабатывание или пропуск — сначала пример сюда, потом правка слов.

Датчик получает текст после normalize_text: нижний регистр, без знаков препинания, ё → е.
Слова сравнивает contains_keyword: фраза из нескольких слов — по целым словам подряд, одно слово
длиннее трёх букв — как часть слова («аллергическ» ловит «аллергическая»), короче — только целиком.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Collection

from .extractors import contains_keyword


@dataclass(frozen=True)
class Detector:
    name: str
    check: Callable[[str], bool]
    examples_yes: tuple[str, ...]
    examples_no: tuple[str, ...] = ()

    def __call__(self, normalized: str) -> bool:
        return self.check(normalized)


def _words(words: Collection[str], *, unless: Collection[str] = ()) -> Callable[[str], bool]:
    return lambda text: contains_keyword(text, words) and not (unless and contains_keyword(text, unless))


